import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire('C:/Users/Fahmi Aufa/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json');
const {chromium}=require('playwright');
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.isMainPageReady&&document.body.style.overflow!=='hidden');
await page.locator('.studio-link[href="#projects"]').click();
await page.waitForFunction(()=>location.hash==='#projects'&&!document.documentElement.classList.contains('is-colonnade-transitioning')&&document.querySelector('#projects').dataset.entryPhase==='idle');
const index=await page.locator('.orbit-card[data-center="true"]').getAttribute('data-index');
const card=page.locator(`.orbit-card[data-index="${index}"]`);
const box=await card.boundingBox();await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.waitForTimeout(1400);
assert.equal(await card.locator('img').first().evaluate(el=>el.style.filter),'none');
await page.mouse.click(box.x+box.width/2,box.y+box.height/2);await page.waitForTimeout(1800);
assert.equal(await page.locator('#project-gallery').evaluate(el=>el.open),true);
await page.keyboard.press('Escape');await page.waitForTimeout(1800);
assert.equal(await page.locator('#project-gallery').evaluate(el=>el.open),false);
assert.equal(await page.evaluate(()=>document.body.style.overflow==='hidden'),false);
await page.locator('.studio-link[href="#about"]').click();
await page.waitForFunction(()=>location.hash==='#about'&&!document.documentElement.classList.contains('is-colonnade-transitioning'));
assert.equal(await page.locator('.studio-link[href="#about"]').getAttribute('aria-current'),'location');
assert.deepEqual(errors,[]);console.log('PASS: navigation, color hover, detail, Escape, scroll unlock, return About');await browser.close();
